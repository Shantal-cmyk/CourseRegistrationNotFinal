    private void dropCourseBtnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_dropCourseBtnActionPerformed
        int row = studenttable.getSelectedRow();

        if (row == -1) {
            JOptionPane.showMessageDialog(this, "Please select a course first.");
            return;
        }

        String code = studenttable.getValueAt(row, 1).toString();

        int confirm = JOptionPane.showConfirmDialog(
                this,
                "Are you sure you want to drop " + code + "?",
                "Drop Course",
                JOptionPane.YES_NO_OPTION
        );

        if (confirm == JOptionPane.YES_OPTION) {

            DBConn db = new DBConn();

            boolean dropped = db.dropCourse(loggedInStudentID, code);

            if (dropped) {
                JOptionPane.showMessageDialog(this, "Course dropped successfully!");

                studenttable.setModel(
                        db.getMyCourses(loggedInStudentID)
                );
            } else {
                JOptionPane.showMessageDialog(this, "Failed to drop course.");
            }
        }
    }//GEN-LAST:event_dropCourseBtnActionPerformed

