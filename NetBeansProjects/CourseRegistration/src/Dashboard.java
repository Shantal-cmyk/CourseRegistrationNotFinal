    private void registerActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_registerActionPerformed

        String studentIDValue = studentID.getText().trim();
        String codeValue = code.getText().trim();
        String scheduleValue = schedule.getText().trim();
        String subjectValue = subject.getSelectedItem().toString();
        String teacherValue = teacher.getSelectedItem().toString();

        String statusValue;

        if (active.isSelected()) {
            statusValue = "Active";
        } else {
            statusValue = "Inactive";
        }
        if (studentIDValue.isEmpty()
                || codeValue.isEmpty()
                || scheduleValue.isEmpty()) {

            JOptionPane.showMessageDialog(
                    this,
                    "Please complete all required fields."
            );

            return;
        }

        javax.swing.table.DefaultTableModel model
                = (javax.swing.table.DefaultTableModel) studenttable.getModel();

        model.addRow(new Object[]{
            studentIDValue,
            codeValue,
            subjectValue,
            scheduleValue,
            teacherValue,
            statusValue
        });

        JOptionPane.showMessageDialog(
                this,
                "Course registered successfully!"
        );

        addRegisterModal.setVisible(false);

    }//GEN-LAST:event_registerActionPerformed

